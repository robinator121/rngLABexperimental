rc = rp.rc
NAMESPACE = "rnglab-v019-audit-smoke"


def oracle_call_scan() -> dict:
    """Where the frozen oracle call (scipy.stats.nct) is not finite, and its accuracy where it is."""
    grid = np.round(np.arange(0.0, 45.0001, 0.05), 2)
    nan, worst = [], 0.0
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        for delta in grid:
            frozen = rc.validity_probability_frozen(float(delta))
            if math.isfinite(frozen):
                worst = max(worst, abs(frozen - rc.validity_probability_stable(float(delta))))
            else:
                nan.append(float(delta))
    return {"grid": [0.0, 45.0, 0.05], "points": len(grid), "not_finite": len(nan),
            "first_not_finite": min(nan) if nan else None, "last_not_finite": max(nan) if nan else None,
            "share_not_finite_between_first_and_last": (len(nan) / (round((max(nan) - min(nan)) / 0.05) + 1)) if nan else None,
            "max_abs_error_where_finite": worst,
            "stable_value_at_first_not_finite": rc.validity_probability_stable(min(nan)) if nan else None,
            "delta_where_stable_value_is_1e-3": float(next(d for d in grid if rc.validity_probability_stable(float(d)) < 1e-3))}


def power_versus_product(count: int = 1_000_000) -> dict:
    """How often libm pow(x, 2), which the sampler uses for scalars, differs from the rounded product x*x."""
    rng = np.random.default_rng(20261111)
    x = rng.normal(size=count) * rng.choice([1e-3, 1.0, 37.0], size=count)
    python_power = np.array([value ** 2 for value in x.tolist()])
    numpy_scalar = np.array([float(np.float64(value) ** 2) for value in x[:200_000].tolist()])
    return {"values": count, "python_float_power_differs_from_product": int(np.count_nonzero(python_power != x * x)),
            "share": float(np.mean(python_power != x * x)),
            "numpy_scalar_power_equals_python_power": bool(np.array_equal(numpy_scalar, python_power[:200_000])),
            "libc": " ".join(platform.libc_ver())}


def gates() -> dict:
    v2d = max(k for k in range(0, 400) if rc.gate_v2d(k)["pass"])
    accepted = [k for k in range(1700, 2001) if rc.criterion_1({0: k})["result"] == "PASS"]
    design = json.loads((REPO / "research/v019-d-pilot/design.json").read_text())
    onsets = np.arange(2048, 8193)
    shares = []
    for row in design["ramp_profiles"]["lengths"]:
        room = np.clip(row["L"] - onsets - 1, 2048, 163840).astype(float)
        exact = float(np.mean(np.log(room / 2048) / math.log(163840 / 2048)))
        shares.append({"L": row["L"], "design_simulation": row["share_reaching_cap_before_L"], "exact": exact,
                       "difference_in_standard_errors": (row["share_reaching_cap_before_L"] - exact)
                       / math.sqrt(exact * (1 - exact) / design["ramp_profiles"]["draws"])})
    c4 = math.sqrt(2 / 15) * math.exp(special.gammaln(8.0) - special.gammaln(7.5))
    return {"V2_D_largest_passing_alarm_count_of_2000": v2d, "V2_D_cp95_upper_at_that_count": rc.gate_v2d(v2d)["cp95"][1],
            "criterion_1_accepted_counts": [accepted[0], accepted[-1]],
            "criterion_1_pass_probability": {str(p): float(stats.binom.cdf(accepted[-1], 2000, p) - stats.binom.cdf(accepted[0] - 1, 2000, p))
                                             for p in (0.93, 0.94, 0.95)},
            "ramp_cap_shares": shares,
            "sigma_eff_mean_of_standard_errors_bias_factor": c4,
            "calibration_false_alarm_rate_given_threshold_sd": math.sqrt(0.05 * 0.95 / 1001)}


def full_length_runs() -> dict:
    """Byte consumption, window sizes and the SHIFT target statistic on four regenerated full-length runs."""
    out = {}
    for family in ("healthy", "SHIFT", "LAG1", "DUP"):
        condition = "healthy" if family == "healthy" else "fault/" + family
        run = rp.replay(NAMESPACE, condition, family, 0)
        marks = run["marks"]
        per_sweep = np.diff(marks, prepend=0)
        bits = np.array([64 * (hi - lo) for lo, hi in (rc.window_words(marks, e - 512, e) for e in rc.BATTERY_ENDS)])
        row = {"local_bytes": int(run["local_bytes"]), "bytes_per_sweep_mean": float(per_sweep.mean()),
               "uphill_fraction": float(((per_sweep - 128) / 128).mean()), "window_bits_min": int(bits.min()),
               "window_bits_max": int(bits.max()), "windows_over_bit_cap": int(np.sum(bits > rc.BIT_CAP_BITS)),
               "windows_below_750000_bits": int(np.sum(bits < 750000)),
               "uphill_fraction_needed_for_a_cut": (rc.BIT_CAP_BITS / 8 / 512 - 128) / 128}
        if family == "SHIFT":
            words, severity = run["emitted_words"], run["severity"]
            top = np.uint64(0xFFFFFFFFFFFFF800)
            rows = []
            for end in rc.BATTERY_ENDS:
                lo, hi = rc.window_words(marks, end - 512, end)
                window = words[lo:hi]
                saturated = int(np.count_nonzero((window & top) == top))
                z, _ = rc.frequency_test(np.unpackbits(np.frombuffer(rc.words_to_bytes(window), dtype=np.uint8)))
                rows.append((int(end), float(severity[end - 512:end].mean()), saturated / len(window), z, len(window)))
            table = np.array(rows)
            post = table[:, 1] > 0
            fit = float(np.sum(table[post, 1] * table[post, 2]) / np.sum(table[post, 1]**2))
            small = post & (table[:, 1] < 0.002)
            row["shift_saturation"] = {
                "t0": run["t0"], "windows_after_onset": int(post.sum()),
                "saturated_fraction_per_unit_mean_severity": fit,
                "saturated_fraction_before_onset_max": float(table[~post, 2].max()),
                "frequency_z_per_unit_mean_severity": float(np.sum(table[post, 1] * table[post, 3]) / np.sum(table[post, 1]**2)),
                "windows_with_mean_severity_below_0.002": int(small.sum()),
                "frequency_z_in_those_windows_mean": float(table[small, 3].mean()) if small.any() else None,
                "saturated_words_in_those_windows_mean": float((table[small, 2] * table[small, 4]).mean()) if small.any() else None}
        out[family] = row
    return out


def campaign_cost() -> dict:
    path = _HERE / "results/benchmark.json"
    if not path.is_file():
        return {"status": "benchmark.json not present"}
    bench = json.loads(path.read_text())
    single = {r["family"]: r for r in bench["single"]}
    slowdown = float(np.mean(bench["parallel"]["slowdown_per_job"]))
    workers = bench["parallel"]["workers"]

    def seconds(family, stages):
        return sum(single[family].get(s + "_seconds", 0.0) for s in stages)

    healthy = seconds("healthy", ("generate", "measure", "write"))
    fault = float(np.mean([seconds(f, ("generate", "measure", "write", "check_i2", "check_i3")) for f in ("SHIFT", "LAG1", "DUP")]))
    fault_vector = float(np.mean([seconds(f, ("generate", "measure", "write", "check_i2", "vector_transform")) for f in ("SHIFT", "LAG1", "DUP")]))
    alone = 2999 * healthy + 3000 * fault
    record = float(np.mean([r["record_file_bytes"] for r in bench["single"]]))
    trace = float(np.mean([r["trace_file_bytes"] for r in bench["single"]]))
    return {"measure_layer_sha256": bench["measure_layer"]["sha256"], "workers_in_benchmark": workers,
            "mean_slowdown_per_job_at_those_workers": slowdown,
            "worker_seconds_alone": {"healthy_run": healthy, "fault_run": fault, "fault_run_with_vectorised_i3": fault_vector},
            "campaign_worker_hours_if_alone": alone / 3600,
            "campaign_wall_hours_at_benchmark_parallelism": alone * slowdown / workers / 3600,
            "campaign_wall_hours_with_vectorised_i3": (2999 * healthy + 3000 * fault_vector) * slowdown / workers / 3600,
            "protocol_extrapolation_wall_hours_8_workers": 235.782388705994 / 60,
            "bytes_per_run": {"record_json": record, "trace_npz": trace},
            "campaign_bytes": {"records": 5999 * record, "traces": 5999 * trace, "total_GiB": 5999 * (record + trace) / 2**30,
                               "protocol_trace_baseline_GiB": 5.49224853515625},
            "independent_verification_seconds_per_run": float(np.mean([r["verify_seconds"] for r in bench["single"]])),
            "independent_replay_seconds_per_run": float(np.mean([r["replay_seconds"] for r in bench["single"]])),
            "peak_rss_MiB": max(r["rss_peak_kb"] for r in bench["single"]) / 1024}


def main() -> int:
    out = {"schema": "rnglab-v019-audit-numbers-v1", "namespace": NAMESPACE,
           "environment": {"python": platform.python_version(), "numpy": np.__version__,
                           "scipy": __import__("scipy").__version__, "libc": " ".join(platform.libc_ver())},
           "oracle_call": oracle_call_scan(), "power_versus_product": power_versus_product(), "gates": gates(),
           "full_length_runs": full_length_runs(), "campaign_cost": campaign_cost()}
    target = _HERE / "results/audit_numbers.json"
    target.parent.mkdir(exist_ok=True)
    target.write_text(json.dumps(out, indent=1, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    print(json.dumps(out, indent=1, sort_keys=True)[:6000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
