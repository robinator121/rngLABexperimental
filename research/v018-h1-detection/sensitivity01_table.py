#!/usr/bin/env python3
"""Tables for SENSITIVITY_01_RESULTS.md, from results/sensitivity01.json and results/gates.json. No new statistics.

    python research/v018-h1-detection/sensitivity01_table.py

Writes results/sensitivity01_table.md.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def ci(pair, digits=3):
    return f"[{pair[0]:.{digits}f}, {pair[1]:.{digits}f}]"


def main() -> None:
    s = json.loads((HERE / "results" / "sensitivity01.json").read_text())
    g = json.loads((HERE / "results" / "gates.json").read_text())
    h = s["healthy_C_prime"]
    lines = [
        "# Sensitivity 01 tables (generated by `sensitivity01_table.py`)", "",
        f"- Freeze: HEAD {s['freeze']['HEAD'][:7]}; files last changed at "
        + ", ".join(f"`{Path(k).name}` {v['last_changed_commit'][:7]}" for k, v in s["freeze"]["files"].items()),
        f"- Self-check identical: {s['self_check']['identical']}",
        f"- τ_C′ = {s['thresholds']['tau_C_prime']:.6g} (Stage C τ_C = {g['thresholds']['C']:.6g}); "
        f"τ_A unchanged: {s['thresholds']['tau_A_matches_stage_c']}",
        f"- Healthy whole-run C′ alarms: {h['alarms']}/{h['runs']} ({h['alarms'] / h['runs']:.6g}), CP95 {ci(h['cp95'], 4)}; "
        f"V2 rule: {'PASS' if s['v2_c_prime_pass'] else 'FAIL'}; V1: {s['V1']['result']}; "
        f"implementation checks: {'PASS' if s['implementation_checks_pass'] else 'FAIL'}; interpretable: {s['interpretable']}",
        f"- Verdicts under C′: " + ", ".join(f"{f} {v}" for f, v in s["verdicts_c_prime"].items()),
        f"- Cells in H1 or undetected_harm under C′: {s['cells_h1_or_undetected_harm'] or 'none'}", "",
        "Intervals are Clopper–Pearson (alarms, wrong) or paired bootstrap (gap) at the Bonferroni level 1 − 0.05/24.", "",
        "| Cell | Wrong k/n (rate) | Wrong CI | C alarms (Stage C) | C′ alarms | C′ CI | A alarms | Pass-but-broken C → C′ "
        "| A − C′ mean | A − C′ CI | Class C → C′ |",
        "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in s["cells"].items():
        old = g["cells"][name]
        w, a = c["wrong"], c["C_prime_alarm"]
        change = c["class_stage_c"] if not c["class_changed"] else f"{c['class_stage_c']} → **{c['class_c_prime']}**"
        lines.append(f"| {name} | {w['k']}/{w['n']} ({w['rate']:.3f}) | {ci(w['cp_bonferroni'])} | {old['C_alarm']['k']} "
                     f"| {a['k']} | {ci(a['cp_bonferroni'])} | {c['A_alarm']['k']} | {old['pass_but_broken']} → {c['pass_but_broken']} "
                     f"| {c['A_minus_C_prime']['mean']:.3f} | {ci(c['A_minus_C_prime']['ci_bonferroni'])} | {change} |")
    lines += ["", "**First-firing SP 800-22 test under C′** (runs with a post-onset C′ alarm; descriptive):", ""]
    lines += [f"- {name}: " + ", ".join(f"{k} {v}" for k, v in sorted(c["first_firing_sp80022"].items(), key=lambda kv: -kv[1]))
              for name, c in s["cells"].items() if c["first_firing_sp80022"]]
    (HERE / "results" / "sensitivity01_table.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
