"""Markdown tables for the Stage C (H1) report, from the analysis outputs.

RNGLab v0.18 (written by OpenAI Codex, gpt-6-astra, 2026-11-07; reviewed by Claude Code)
Reads results/gates.json, results/secondary.json, results/recount.json and,
if present, results/run_manifest.json; writes results/report_tables.md.
Formats stored results only; no intervals or verdicts are recomputed.

    python research/v018-h1-detection/report_tables.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
FAMILIES = ("SHIFT", "LAG1", "DUP", "GFSR")


def f(x):
    return "—" if x is None else f"{x:.6g}"


def ci(pair):
    return "—" if pair is None else f"[{f(pair[0])}, {f(pair[1])}]"


def severity(value):
    return ",".join(map(str, value)) if isinstance(value, list) else f(value)


def cell_key(item):
    name, cell = item
    value = cell["severity"]
    return FAMILIES.index(cell["family"]), tuple(value) if isinstance(value, list) else (value,), name


def rate(k, n):
    return f"{k}/{n} ({f(k / n) if n else '—'})"


def table(out, title, columns, rows):
    out.extend([f"## {title}", "", "| " + " | ".join(columns) + " |",
                "|" + "---|" * len(columns)])
    for row in rows:
        out.append("| " + " | ".join(str(v).replace("|", "\\|").replace("\n", " ") for v in row) + " |")
    out.append("")


def main():
    g = json.loads((RESULTS / "gates.json").read_text())
    s = json.loads((RESULTS / "secondary.json").read_text())
    rc = json.loads((RESULTS / "recount.json").read_text())
    manifest = RESULTS / "run_manifest.json"
    run = json.loads(manifest.read_text()) if manifest.exists() else None
    inputs = "`results/gates.json`, `results/secondary.json`, `results/recount.json`"
    if run is not None:
        inputs += " and `results/run_manifest.json`"
    out = ["# Stage C (H1) report tables", "", f"Generated by `report_tables.py` from {inputs}.", ""]
    cells = sorted(g["cells"].items(), key=cell_key)

    rows = []
    for key, field, criterion in (("I-1", "failing_runs", "Zero failing sweep clocks"),
                                  ("I-2", "mismatched_prefixes", "Zero mismatched prefixes"),
                                  ("I-3", "cells", "Every fault realization matches"),
                                  ("I-4", "cells", "Every replay matches")):
        check = g["implementation"][key]
        value = check[field]
        if isinstance(value, dict):
            value = "; ".join(f"{name}: {ok}" for name, ok in value.items()) or "—"
        else:
            value = f"{field}: {value}"
        rows.append([key, criterion, value, "—", check["result"]])
    v1, v2 = g["validity"]["V1"], g["validity"]["V2"]
    rows.append(["V1", "CP95 inside [0.92, 0.98]", rate(v1["covered"], v1["runs"]) +
                 f"; onset_flagged: {v1['onset_flagged']}", ci(v1["cp95"]), v1["result"]])
    for arm in ("C", "A"):
        q = v2[f"rate_{arm}"]
        rows.append([f"V2 {arm}", "Both arms' whole-run CP95 upper ≤ 0.10",
                     rate(q["alarms"], q["runs"]), ci(q["cp95"]), v2["result"]])
    rows.append(["V2 paired A-minus-C", "Descriptive", f(v2["paired_A_minus_C"]),
                 ci(v2["paired_ci95"]), "—"])
    for arm, value in g["thresholds"].items():
        rows.append([f"Threshold {arm}", "Alarm when score > threshold", f(value), "—", "—"])
    rows.append(["Bonferroni level", "Stored campaign confidence level", f"{g['bonferroni_level']:.12g}", "—", "—"])
    table(out, "T1. Implementation checks, validity gates and thresholds",
          ["Check / setting", "Criterion / meaning", "Value", "95% interval", "Result"], rows)

    rows = []
    for name, c in cells:
        w, a, conv, gap = c["wrong"], c["A_alarm"], c["C_alarm"], c["A_minus_C"]
        rows.append([name, c["family"], severity(c["severity"]), rate(w["k"], w["n"]),
                     ci(w["cp_bonferroni"]), ci(w["cp95"]), rate(conv["k"], c["runs"]),
                     ci(conv["cp_bonferroni"]), rate(a["k"], c["runs"]), ci(a["cp_bonferroni"]),
                     f(gap["mean"]), ci(gap["ci_bonferroni"]), c["pass_but_broken"], c["class"]])
    table(out, "T2. Fault cells", ["Cell", "Family", "Severity", "Wrong k/n (rate)", "Wrong CP Bonferroni",
          "Wrong CP95", "C-alarm k/n (rate)", "C CP Bonferroni", "A-alarm k/n (rate)", "A CP Bonferroni",
          "A-minus-C mean", "A-minus-C Bonferroni interval", "pass_but_broken", "Class"], rows)
    out += ["Alarm counts are post-onset. Wrong denominators exclude onset-flagged runs. "
            "CP denotes Clopper–Pearson; the paired difference uses the stored bootstrap interval.", ""]

    v = g["verdicts"]
    rows = [[family, v["H1-C"].get(family, "—")] for family in FAMILIES]
    rows += [[key, v[key]] for key in ("interpretable", "implementation_checks_pass")]
    table(out, "T3. H1-C verdicts", ["Family / flag", "Stored verdict / value"], rows)
    out += ["Family verdicts are not interpretable when interpretable is False. "
            "A dash means the family is absent from the stored verdicts.", ""]

    rows = []
    for name, c in cells:
        lat = c["latency"]
        sw, by = lat["sweeps"], lat["bytes"]
        rows.append([name, sw["both"], f(sw["median_A_minus_C"]), ci(sw["ci95"]),
                     f(by["median_A_minus_C"]), ci(by["ci95"]), lat["only_C"], lat["only_A"], lat["neither"]])
    table(out, "T4. Latency among runs where both arms detect", ["Cell", "Both detect", "Median A-minus-C (sweeps)",
          "95% interval (sweeps)", "Median A-minus-C (bytes)", "95% interval (bytes)", "only_C", "only_A", "neither"], rows)
    out += ["Positive A-minus-C means A detects later. A dash denotes an unavailable median or interval.", ""]

    rows = []
    names = (["healthy"] if "healthy" in s["cells"] else []) + [name for name, _ in cells]
    for name in names:
        c = s["cells"][name]
        firing = "; ".join(f"{key}: {value}" for key, value in sorted(c["first_firing_conventional_test"].items())) or "—"
        rows.append([name, c["runs"], *[c["post_onset_alarms"][key] for key in ("A1", "A2", "shape", "cusum_D")],
                     firing, c["health_test_post_onset_alarm_runs"], f(c["mean_cv_bias"]), c["td_wrong"]])
    table(out, "T5. Secondaries (descriptive, no gates)", ["Cell", "Runs", "A1 post-onset alarms", "A2 post-onset alarms",
          "Shape post-onset alarms", "cusum_D post-onset alarms", "First-firing conventional test counts",
          "Health-test post-onset alarm runs", "Mean CV bias", "TD wrong"], rows)

    comparisons = rc["comparisons"]
    table(out, "T6. Independent recount", ["Agreeing comparisons / total", "all_agree"],
          [[f"{sum(c['agree'] for c in comparisons)}/{len(comparisons)}", rc["all_agree"]]])
    if run is not None:
        fields = ("first_start_utc", "workers", "git_head_at_run")
        out += ["Run manifest: " + "; ".join(f"{key}: {run[key]}" for key in fields if key in run) + ".", ""]
    (RESULTS / "report_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote results/report_tables.md")


if __name__ == "__main__":
    main()
