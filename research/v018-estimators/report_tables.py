#!/usr/bin/env python3
"""Markdown tables for REPORT.md, generated from the analysis outputs.

RNGLab v0.18 (written by Claude Code, 2026-11-05). Reads results/gates.json,
results/ar1_table.csv and results/recount.json; writes results/report_tables.md.
Every number in REPORT.md's tables is copied from that file.

    python research/v018-estimators/report_tables.py
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "results" / "gates.json").read_text())
G, A = R["gates"], R["amendment_01_secondary"]
CELLS = [f"ising_L{L}_{t}" for L in (2, 3, 4) for t in ("T1.5", "Tc", "T3.5")]


def f(x, d=4):
    return f"{x:.{d}f}"


def ci(pair, d=4):
    return f"[{f(pair[0], d)}, {f(pair[1], d)}]"


def cov(c):
    return f"{c['covered']}/{c['units']} ({f(c['coverage'], 3)}; {ci(c['cp95'], 3)})"


def main():
    out = ["# Phase 1 report tables", "", "Generated by `report_tables.py` from `results/gates.json`, "
           "`results/ar1_table.csv` and `results/recount.json`.", ""]
    out += ["## T1. Susceptibility (Ising, 32,768 chains per cell; G uses 2,048 ensembles of 16)", "",
            "| Cell | χ exact | P rel. bias | S coverage | S rel. bias CI | S var. ratio CI | S-S | G coverage | G rel. bias CI | G var. ratio CI | S-G |",
            "|---|---:|---:|---|---|---|---|---|---|---|---|"]
    for cell in CELLS:
        s, g = G[f"S-S[{cell}]"], G[f"S-G[{cell}]"]
        chi = next(r for r in csv.DictReader((HERE / "results" / "ising_table.csv").open()) if r["cell"] == cell)
        out.append(f"| {cell[6:]} | {f(float(chi['chi_exact']))} | {f(float(chi['P_bias']), 3)} | {cov(s['coverage'])} | "
                   f"{ci(s['relative_bias']['ci95'], 5)} | {ci(s['variance_ratio']['ci95'], 3)} | {s['result']} | "
                   f"{cov(g['coverage'])} | {ci(g['relative_bias']['ci95'], 5)} | {ci(g['variance_ratio']['ci95'], 3)} | {g['result']} |")
    out += ["", "## T2. Failure-reproduction gates", "", "| Gate | Data | Value | Criterion | Result |", "|---|---|---|---|---|"]
    out.append(f"| S-F1 | L4 T1.5, plug-in P | relative bias {f(G['S-F1']['relative_bias_P']['mean'], 4)}, CI {ci(G['S-F1']['relative_bias_P']['ci95'])} | CI upper < −0.5 | {G['S-F1']['result']} |")
    for k in ("L-F1", "L-F2"):
        out.append(f"| {k} | {G[k]['data']}, BM(32) | coverage {cov(G[k]['BM(32)'])} | CP95 upper < 0.92 | {G[k]['result']} |")
    d = G["D-F1"]["rhat_m_not_converged"]
    out.append(f"| D-F1 | L4 T1.5, split-R̂ of m > 1.01 | {d['covered']}/{d['units']} ensembles, CP95 {ci(d['cp95'])} | CP95 lower ≥ 0.90 | {G['D-F1']['result']} |")
    out += ["", "## T3. Long-run variance gates (AR(1), n = 8192, 4,096 replicas)", "",
            "| Gate | Coverage | Variance ratio vs exact (bootstrap CI) | Result |", "|---|---|---|---|"]
    for k, v in G.items():
        if k.startswith(("L-A[", "L-G[")):
            vr = v["variance_ratio_vs_exact"]
            out.append(f"| {k} | {cov(v['coverage'])} | {f(vr['ratio'], 3)} {ci(vr['ci95'], 3)} | {v['result']} |")
    out += ["", "## T4. Diagnostic-gated adaptive estimators (L-D)", "",
            "| φ | n | Non-abstaining (of 4,096) | BM | OBM | SV-TH | Result (BM/OBM/SV-TH) |", "|---|---|---:|---|---|---|---|"]
    for phi in ("0.0", "0.5", "0.9", "0.99", "0.997"):
        for n in ("8192", "65536"):
            row = [G[f"L-D[{phi},{n},{fam}]"] for fam in ("BM", "OBM", "SV-TH")]
            cells = [f(r["coverage"]["coverage"], 4) if r["result"] != "NOT_EVALUABLE" else "—" for r in row]
            out.append(f"| {phi} | {n} | {row[0]['non_abstaining']} | {cells[0]} | {cells[1]} | {cells[2]} | "
                       f"{'/'.join(r['result'] for r in row)} |")
    out += ["", "## T5. Control gates", "",
            "| Gate | Empirical/exact Var(x̄) (bootstrap CI) | Mean x̄ CI | Frozen result | Amendment 01 adjusted view flags |",
            "|---|---|---|---|---|"]
    for k, v in G.items():
        if k.startswith("L-C["):
            name = k[4:-1]
            out.append(f"| {k} | {f(v['empirical_over_exact_var'], 3)} {ci(v['ci95'], 3)} | {ci(v['mean_xbar']['ci95'], 5)} | "
                       f"{v['result']} | {A['L-C_adjusted'][name]['flagged']} |")
    out += ["", "| Gate | Relative energy bias CI | Result |", "|---|---|---|"]
    for cell in CELLS:
        v = G[f"S-C[{cell}]"]
        out.append(f"| S-C[{cell[6:]}] | {ci(v['relative_bias_energy']['ci95'], 5)} | {v['result']} |")
    out += ["", "## T6. Secondary: long autocorrelation (no gates)", "",
            "| Setting | τ_n | Method | b | Coverage | Var. ratio | Median ESS-hat/true |", "|---|---:|---|---:|---:|---:|---:|"]
    for r in csv.DictReader((HERE / "results" / "ar1_table.csv").open()):
        if r["phi"] in ("0.99", "0.997") and (r["b"] in ("512", "1024") or r["method"] == "GEYER"):
            out.append(f"| {r['setting']} | {float(r['tau_n']):.1f} | {r['method']} | {r['b'] or '—'} | {f(float(r['coverage']), 4)} | "
                       f"{f(float(r['var_ratio']), 3)} | {f(float(r['median_ess_over_true']), 3)} |")
    out += ["", "## T7. Amendment 01 checks", "", "| Cell | max |ΔR̂| m | flagged m (orig → amended) | split-half m² (rel. χ) CI | split-half energy CI |",
            "|---|---:|---|---|---|"]
    for cell in CELLS:
        c = A["rhat_original_vs_amended"][cell]["m"]
        s = A["split_half_burn_in"][cell]
        out.append(f"| {cell[6:]} | {c['max_abs_difference_finite']:.2e} | {c['original_flagged']} → {c['amended_flagged']} | "
                   f"{ci(s['second_minus_first_m2_relative_to_chi']['ci95'], 5)} | {ci(s['second_minus_first_energy_relative']['ci95'], 5)} |")
    rc = json.loads((HERE / "results" / "recount.json").read_text())
    out += ["", f"Independent recount (`recount.py`): {sum(c['agree'] for c in rc['comparisons'])}/{len(rc['comparisons'])} "
            f"primary counts agree; all_agree = {rc['all_agree']}.", ""]
    (HERE / "results" / "report_tables.md").write_text("\n".join(out))
    print("wrote results/report_tables.md")


if __name__ == "__main__":
    main()
