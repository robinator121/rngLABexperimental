#!/usr/bin/env python3
"""Markdown tables for the Phase 2 REPORT.md, generated from the analysis outputs.

RNGLab v0.18 (written by Claude Code, 2026-11-06). Reads results/gates.json,
results/secondary.json, results/recount.json and results/run_manifest.json;
writes results/report_tables.md. Every number in REPORT.md's tables is copied
from that file.

    python research/v018-api-validation/report_tables.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
NAMES = {"local": "Local Metropolis", "refresh": "Local + centroid refresh", "iid": "IID Gaussian paths"}


def f(x, d=4):
    return f"{x:.{d}f}"


def ci(pair, d=4):
    return f"[{f(pair[0], d)}, {f(pair[1], d)}]"


def main():
    g = json.loads((RESULTS / "gates.json").read_text())
    s = json.loads((RESULTS / "secondary.json").read_text())
    rc = json.loads((RESULTS / "recount.json").read_text())
    run = json.loads((RESULTS / "run_manifest.json").read_text())
    p = g["primary"]
    out = ["# Phase 2 report tables", "",
           "Generated by `report_tables.py` from `results/gates.json`, `results/secondary.json`, "
           "`results/recount.json` and `results/run_manifest.json`.", ""]

    out += ["## T1. Primary endpoint: CV with BM512 (16 batches, t15)", "",
            "| Condition | Covered / R | Coverage CP95 | Variance ratio (bootstrap CI95) | Mean bias (CI95) | Not estimated |",
            "|---|---|---|---|---|---:|"]
    for c in ("local", "refresh", "iid"):
        q = p[c]
        out.append(f"| {NAMES[c]} | {q['covered']}/{q['units']} ({f(q['coverage'])}) | {ci(q['cp95'])} | "
                   f"{f(q['variance_ratio']['ratio'], 3)} {ci(q['variance_ratio']['ci95'], 3)} | "
                   f"{q['bias']['mean']:.6f} {ci(q['bias']['ci95'], 6)} | {q['not_estimated']} |")

    out += ["", "## T2. Gates", "", "| Gate | Criterion | Value | Result |", "|---|---|---|---|"]
    for key, cond in (("G-R", "refresh"), ("G-I", "iid")):
        q = p[cond]
        out.append(f"| {key} coverage | CP95 inside [0.92, 0.98] | {ci(q['cp95'])} | {'PASS' if g[key]['coverage'] else 'FAIL'} |")
        out.append(f"| {key} variance ratio | CI95 inside [0.75, 1.25] | {ci(q['variance_ratio']['ci95'], 3)} | {'PASS' if g[key]['variance_ratio'] else 'FAIL'} |")
        out.append(f"| {key} bias | CI95 inside [−0.01, 0.01] | {ci(q['bias']['ci95'], 6)} | {'PASS' if g[key]['bias'] else 'FAIL'} |")
    out.append(f"| F-L | local CP95 upper < 0.92 | {f(g['F-L']['cp95_upper'])} | {g['F-L']['result']} |")
    out.append(f"| P-RL | paired lower bound > 0.10 | {f(g['P-RL']['mean_difference'])} {ci(g['P-RL']['bootstrap_ci95'])}; "
               f"refresh only {g['P-RL']['improved_only']}, local only {g['P-RL']['local_only']} | {g['P-RL']['result']} |")
    v = g["verdicts"]
    out += ["", f"Verdicts: implementation checks pass = {v['implementation_checks_pass']}; H-API {v['H-API']}; "
            f"H-REP {v['H-REP']}; core result reproduced = {v['core_result_reproduced']}.", ""]

    out += ["## T3. Implementation checks", "", "| Check | Value | Result |", "|---|---|---|"]
    i = g["implementation"]
    out.append(f"| I-1 byte ledger | {i['I-1']['mismatches']} mismatches | {i['I-1']['result']} |")
    out.append(f"| I-2 start pairing | {i['I-2']['mismatched_replicas']} mismatched replicas | {i['I-2']['result']} |")
    out.append(f"| I-3 trace consistency | max abs difference {i['I-3']['max_abs_difference']:.2e} (tolerance 1e-12) | {i['I-3']['result']} |")
    same = sum(x["identical"] for k, x in i["I-4"].items() if isinstance(x, dict))
    out.append(f"| I-4 deterministic replay | {same}/3 identical | {i['I-4']['result']} |")
    out.append(f"| Independent recount | {sum(c['agree'] for c in rc['comparisons'])}/{len(rc['comparisons'])} agree | "
               f"{'PASS' if rc['all_agree'] else 'FAIL'} |")

    out += ["", "## T4. Comparison with Phase II (descriptive)", "",
            "| Condition | API coverage | Phase II coverage | Difference (Wald CI95) |", "|---|---:|---:|---|"]
    for c in ("local", "refresh", "iid"):
        q = s[c]["phase2_comparison"]
        out.append(f"| {NAMES[c]} | {f(q['api_coverage'])} | {f(q['phase2_coverage'])} | {f(q['difference'])} {ci(q['wald_ci95'])} |")

    out += ["", "## T5. Secondary: CV with other variance estimators (coverage; variance ratio)", "",
            "| Method | " + " | ".join(NAMES[c] for c in ("local", "refresh", "iid")) + " |", "|---|---|---|---|"]
    for m in s["local"]["cv_methods"]:
        cells = [f"{f(s[c]['cv_methods'][m]['covered'] / s[c]['cv_methods'][m]['units'])}; "
                 f"{f(s[c]['cv_methods'][m]['variance_ratio'], 3)}" for c in ("local", "refresh", "iid")]
        out.append(f"| {m} | " + " | ".join(cells) + " |")
    out.append("| TD BM512 | " + " | ".join(
        f"{f(s[c]['td_BM512']['covered'] / s[c]['td_BM512']['units'])}; {f(s[c]['td_BM512']['variance_ratio'], 3)}"
        for c in ("local", "refresh", "iid")) + " |")

    out += ["", "## T6. Secondary: batch-length diagnostic, autocorrelation and mechanism", "",
            "| Condition | ADEQUATE / RUN_TOO_SHORT / TAU_UNDEFINED | Adaptive coverage | Geyer τ̂ median [q05, q95] | "
            "Var(CV means) | centroid part | shape part | 2·cov |", "|---|---|---|---|---:|---:|---:|---:|"]
    for c in ("local", "refresh", "iid"):
        d, t, vd = s[c]["diagnostic"], s[c]["geyer_tau_quantiles"], s[c]["variance_decomposition"]
        counts = d["status_counts"]
        adaptive = (f"{d['adaptive_covered']}/{d['adaptive_units']} ({f(d['adaptive_covered'] / d['adaptive_units'])})"
                    if d["adaptive_units"] else "—")
        out.append(f"| {NAMES[c]} | {counts['ADEQUATE']} / {counts['RUN_TOO_SHORT']} / {counts['TAU_UNDEFINED']} | {adaptive} | "
                   f"{t['q50']:.1f} [{t['q05']:.1f}, {t['q95']:.1f}] | {vd['cv_means_variance']:.3e} | {vd['centroid_part']:.3e} | "
                   f"{vd['shape_part']:.3e} | {vd['twice_covariance']:.3e} |")
    acc = {c: s[c]["acceptance_rate_4dp_quantiles"] for c in ("local", "refresh")}
    out += ["", "Acceptance rate (4 dp, legacy rounding), median [q05, q95]: " + "; ".join(
        f"{NAMES[c]} {acc[c]['q50']:.4f} [{acc[c]['q05']:.4f}, {acc[c]['q95']:.4f}]" for c in acc) + ".",
        "", f"Run: {len(run['blocks'])} blocks, {run['workers']} workers, started {run['first_start_utc']}, "
        f"git HEAD {run['git_head_at_run'][:7]}; block seconds total {sum(b['seconds'] for b in run['blocks']):.0f}.", ""]
    (RESULTS / "report_tables.md").write_text("\n".join(out))
    print("wrote results/report_tables.md")


if __name__ == "__main__":
    main()
